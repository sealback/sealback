# Regenerates third_party/age-encryption.js (self-contained ESM bundle of typage)
# and third_party/age-encryption.d.ts (type re-export for tsc, not deployed) from
# the version of age-encryption pinned in package.json.
#
# Usage: npm ci --ignore-scripts && sh scripts/update-third-party.sh
#
# The output is deterministic: CI regenerates it and fails if it differs
# from the committed files.

set -eu

cd "$(dirname "$0")/.."

ENTRY="node_modules/age-encryption/dist/index.js"
FLAGS="--bundle --format=esm --platform=browser --target=es2022 --charset=utf8 --legal-comments=none"

if [ ! -f "$ENTRY" ]; then
  echo "error: $ENTRY not found, run 'npm ci --ignore-scripts' first" >&2
  exit 1
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

node_modules/.bin/esbuild "$ENTRY" $FLAGS \
  --metafile="$tmp/meta.json" --outfile="$tmp/bundle.js" --log-level=warning

# Build the header: package, version, command, and the license notices of
# typage and every package that ended up in the bundle (sorted by name).
node --input-type=module - "$tmp/meta.json" "esbuild $ENTRY $FLAGS" > "$tmp/header.js" <<'EOF'
import { readFileSync } from "node:fs";

const [metaPath, command] = process.argv.slice(2);
const meta = JSON.parse(readFileSync(metaPath, "utf8"));

const names = new Set();
for (const input of Object.keys(meta.inputs)) {
  const m = input.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (!m) throw new Error(`unexpected bundle input: ${input}`);
  names.add(m[1]);
}
const sorted = [...names].sort((a, b) =>
  a === "age-encryption" ? -1 : b === "age-encryption" ? 1 : a < b ? -1 : a > b ? 1 : 0);

const pkg = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8"));
const main = pkg("age-encryption");

const lines = [
  "/*",
  ` * ${main.name} ${main.version} (typage), bundled for Sealback.`,
  " *",
  " * Generated by scripts/update-third-party.sh with:",
  ` *   ${command}`,
  " * Do not edit by hand.",
  " *",
  " * Bundled packages:",
  ...sorted.map((n) => ` *   ${n} ${pkg(n).version} (${pkg(n).license})`),
];
for (const name of sorted) {
  const text = readFileSync(`node_modules/${name}/LICENSE`, "utf8");
  if (text.includes("*/")) throw new Error(`license of ${name} contains "*/"`);
  lines.push(" *", ` * ---- License of ${name} ----`, " *");
  for (const l of text.replace(/\s+$/, "").split(/\r?\n/)) {
    lines.push(l.trimEnd() === "" ? " *" : ` * ${l.trimEnd()}`);
  }
}
lines.push(" */", "");
process.stdout.write(lines.join("\n"));
EOF

mkdir -p third_party
cat "$tmp/header.js" "$tmp/bundle.js" > third_party/age-encryption.js

cat > third_party/age-encryption.d.ts <<'EOF'
// Generated by scripts/update-third-party.sh. Do not edit by hand.
// Type declarations for third_party/age-encryption.js, taken from the pinned
// age-encryption package. Used by tsc only; not deployed.
export * from "../node_modules/age-encryption/dist/index.js";
EOF

echo "third_party/age-encryption.js: $(wc -c < third_party/age-encryption.js) bytes"
